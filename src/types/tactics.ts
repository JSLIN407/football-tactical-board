export type PitchFormat = '8v8' | '11v11';
export type PitchView = 'full' | 'half-attack';
export type PitchTheme = 'turf' | 'slate';
export type TeamSide = 'home' | 'away';

export type PlayerRole =
  | 'GK'
  | 'CB'
  | 'LCB'
  | 'RCB'
  | 'LB'
  | 'RB'
  | 'LWB'
  | 'RWB'
  | 'CDM'
  | 'CM'
  | 'LCM'
  | 'RCM'
  | 'CAM'
  | 'LM'
  | 'RM'
  | 'LW'
  | 'RW'
  | 'CF'
  | 'ST';

export interface PlayerToken {
  id: string;
  team: TeamSide;
  number: number;
  role: PlayerRole;
  label: string;
  /** Normalized horizontal pitch coordinate (0 = left goal line, 100 = right goal line) */
  x: number;
  /** Normalized vertical pitch coordinate (0 = top touchline, 100 = bottom touchline) */
  y: number;
  isGK?: boolean;
}

export interface BallState {
  x: number;
  y: number;
  holderId: string | null;
}

export type AnnotationKind = 'pass' | 'run' | 'dribble' | 'press' | 'zone';

export interface DrawingAnnotation {
  id: string;
  kind: AnnotationKind;
  x1: number;
  y1: number;
  x2: number;
  y2: number;
  team?: TeamSide;
  label?: string;
  autoGenerated?: boolean;
}

export type TacticalPhase = 'on-ball' | 'off-ball' | 'transition' | 'setup';

export interface TacticalKeyframe {
  id: string;
  title: string;
  description: string;
  phase: TacticalPhase;
  players: PlayerToken[];
  ball: BallState;
  annotations: DrawingAnnotation[];
  durationMs: number;
}

export interface TacticalAnalysis {
  summary: string;
  ballStateLabel: string;
  phase: TacticalPhase;
  onBallAction: string;
  offBallAttackShift: string;
  defenseShift: string;
  coachingCue: string;
  detectedIntent: string;
  presetId?: string;
}

export type CanvasTool = 'select' | 'pass' | 'run' | 'dribble' | 'press' | 'zone' | 'erase';

export type SimulationMode = 'auto' | 'on-ball' | 'off-ball';

export interface FormationPreset {
  id: string;
  name: string;
  format: PitchFormat;
  description: string;
  slots: Array<{
    number: number;
    role: PlayerRole;
    label: string;
    /** Coordinates for home team attacking left-to-right (x: 0..50 half, y: 0..100) */
    x: number;
    y: number;
    isGK?: boolean;
  }>;
}

export interface TacticalScenarioPreset {
  id: string;
  title: string;
  format: PitchFormat | 'both';
  mode: 'on-ball' | 'off-ball';
  command: string;
  tag: string;
}
